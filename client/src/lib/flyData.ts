export type FlyType = "dry" | "nymph" | "streamer" | "emerger" | "terrestrial";
export type ConfidenceLevel = "high" | "medium" | "low";
export type RigType = "single" | "dropper" | "indicator" | "streamer_strip";

export interface FlyRigging {
  rod: string;       // e.g. "9 ft · 5-weight"
  reel: string;      // e.g. "Mid-arbor · 5/6 wt"
  line: string;      // e.g. "WF5F (weight-forward floating)"
  leader: string;    // e.g. "9 ft · 4X"
  tippet: string;    // e.g. "5X fluorocarbon (4.4 lb)"
  riggingNote: string; // concise field tip
}

export interface Fly {
  id: string;
  name: string;
  type: FlyType;
  hook: string;
  description: string;
  technique: string;
  bestDepth: string;
  colors: string[];
  imitates: string;
  notes: string;
  rigType: RigType;
  rigging: FlyRigging;
}

export interface HatchEvent {
  insect: string;
  latinName: string;
  peakTime: string;
  duration: string;
  waterTemp: string;
  confidence: ConfidenceLevel;
  flies: string[]; // fly ids
  description: string;
  lookFor: string;
  entomologyNote: string;
}

export interface RegionData {
  name: string;
  rivers: string[];
  hatches: { [month: number]: HatchEvent[] };
}

